import { AnimatePresence, motion } from 'framer-motion'
import { useState } from 'react'
import { cn } from '@/lib/utils'

const tricks = [
  {
    trick: 'The lead misreads a criterion, and the mistake lands in both the test and the code.',
    counter: 'Tests are frozen before delegation, and the reviewer writes its expectations from the ticket alone before reading any test.',
    primary: true,
  },
  {
    trick: 'It deletes a test, loosens an assertion or adds a skip.',
    counter: 'A blocking check fails the build on any removed test, weakened assertion or new skip.',
  },
  {
    trick: 'It declares green without being green.',
    counter: 'Evidence is files produced by commands. Never a summary written by an agent.',
  },
  {
    trick: 'The evidence does not match the code under review.',
    counter: 'A manifest generated by script ties the evidence to the exact diff and test files.',
  },
  {
    trick: 'It relays the sub-agent report without reading it.',
    counter: 'The lead reads the diff and writes its own summary.',
  },
  {
    trick: 'It edits code that must stay human: theme, design system, config.',
    counter: 'Protected zones are blocked by lint. Changing them requires a high-risk ticket.',
  },
  {
    trick: 'It reinvents a library you already have.',
    counter: 'A short list of approved libraries, and any new dependency is flagged in the pull request.',
  },
  {
    trick: 'Files grow without end.',
    counter: 'A maximum file size in the lint, with a refactor expected in response.',
  },
  {
    trick: 'The reviewer turns complacent.',
    counter: 'Read its logs in the first weeks; the weekly retro hardens its prompt.',
  },
]

export default function Guardrails() {
  const [revealed, setRevealed] = useState<Set<number>>(new Set([0]))

  const toggle = (index: number) =>
    setRevealed((current) => {
      const next = new Set(current)
      if (next.has(index)) next.delete(index)
      else next.add(index)
      return next
    })

  return (
    <div className="not-prose my-8 flex flex-col gap-2">
      <div className="flex items-center justify-between">
        <p className="text-muted-foreground m-0 text-xs">
          {revealed.size} of {tricks.length} countermeasures revealed
        </p>
        <button
          type="button"
          onClick={() => setRevealed(new Set(tricks.map((_, index) => index)))}
          className="text-primary text-xs underline-offset-4 hover:underline"
        >
          Reveal all
        </button>
      </div>
      {tricks.map((item, index) => {
        const isRevealed = revealed.has(index)
        return (
          <button
            key={item.trick}
            type="button"
            onClick={() => toggle(index)}
            aria-expanded={isRevealed}
            className={cn(
              'bg-card flex flex-col rounded-lg border p-3 text-left transition-colors',
              item.primary && 'border-destructive/40',
              isRevealed ? 'border-primary/40' : 'hover:border-primary/30',
            )}
          >
            <span className="flex items-start gap-3">
              <span
                className={cn(
                  'mt-1.5 size-2 shrink-0 rounded-full',
                  item.primary ? 'bg-destructive' : 'bg-muted-foreground/40',
                )}
              />
              <span className="text-foreground grow text-sm">
                {item.primary && <span className="text-destructive mr-1.5 text-xs font-medium">Main risk</span>}
                {item.trick}
              </span>
              <span className="text-muted-foreground shrink-0 text-xs">{isRevealed ? 'Hide' : 'Counter'}</span>
            </span>
            <AnimatePresence initial={false}>
              {isRevealed && (
                <motion.span
                  initial={{ height: 0, opacity: 0 }}
                  animate={{ height: 'auto', opacity: 1 }}
                  exit={{ height: 0, opacity: 0 }}
                  className="block overflow-hidden"
                >
                  <span className="text-foreground/80 border-primary/40 mt-2 ml-5 block border-l-2 pl-3 text-sm">
                    {item.counter}
                  </span>
                </motion.span>
              )}
            </AnimatePresence>
          </button>
        )
      })}
    </div>
  )
}
